STATIONS_DICT = {s["code"]: s for s in STATIONS}
ZONES = sorted(set(s["zone"] for s in STATIONS))


def get_station(code):
    return STATIONS_DICT.get(code.upper())


def haversine(lat1, lon1, lat2, lon2):
    from math import radians, sin, cos, sqrt, atan2
    R = 6371
    dlat = radians(lat2 - lat1)
    dlon = radians(lon2 - lon1)
    a = sin(dlat/2)**2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon/2)**2
    c = 2 * atan2(sqrt(a), sqrt(1 - a))
    return R * c


def get_nearby_stations(lat, lon, radius_km=100):
    result = []
    for s in STATIONS:
        dist = haversine(lat, lon, s["lat"], s["lon"])
        if dist <= radius_km:
            result.append({**s, "distance_km": round(dist, 1)})
    return sorted(result, key=lambda x: x["distance_km"])
